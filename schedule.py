# schedule.py — the digest and weekly-summary schedule a profile needs (PUB-08)
#
# GitHub cron is UTC and knows nothing of daylight time. Instead of one line
# that someone swaps at each switch, a workflow carries one cron line per UTC
# offset its zone uses, and every line fires. A run started by one of them
# passes --scheduled; slot_guard() then lets through only the line whose fire
# time is the intended one for that day and the other (its "DST twin", an hour
# away) exits 0 without touching anything.
#
#   python main.py cron            # print each workflow's schedule block and a diff
#   python main.py cron --write    # rewrite the schedule: blocks in place
#
# Standard library only, like profile_loader: the lead time and the guard
# window are passed in (config.CRON_LEAD_MINUTES, SLOT_GUARD_MINUTES).

import re
from collections import namedtuple
from datetime import datetime, time, timedelta, timezone
from pathlib import Path
from zoneinfo import ZoneInfo

CRON_DAYS = ("Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday")
# How far ahead offsets are sampled: a full year of switches plus a margin.
SAMPLE_DAYS = 400
DEFAULT_WEEKLY_TIME = "08:00"
GENERATED_COMMENT = "# generated by `python main.py cron --write` from profile.yaml; do not hand-edit"

ROOT = Path(__file__).resolve().parent
# Workflow file per schedule; fetch.yml is not here: its slots are UTC by design.
WORKFLOWS = {"digest": ROOT / ".github" / "workflows" / "daily.yml",
             "weekly": ROOT / ".github" / "workflows" / "weekly_summary.yml"}

# A schedule: local wall-clock minutes past midnight it fires at, and the days.
Slot = namedtuple("Slot", "minutes days")
# One cron line: the UTC offset it serves and the line itself.
Line = namedtuple("Line", "offset cron")


def _hhmm(text):
    h, m = (int(x) for x in text.split(":"))
    return h * 60 + m


def offsets(tz, start=None, days=SAMPLE_DAYS):
    """Distinct UTC offsets `tz` uses, sampled at local noon on each of the
    next `days` days, lowest first."""
    start = start or datetime.now(timezone.utc).astimezone(tz).date()
    seen = {datetime.combine(start + timedelta(days=i), time(12), tz).utcoffset() for i in range(days)}
    return sorted(seen)


def slots(delivery, lead_minutes):
    """{"digest": Slot, "weekly": Slot} in local wall-clock terms. The digest
    fires `lead_minutes` before delivery.digest_time_local; a lead that crosses
    local midnight fires the day before each digest day."""
    at = _hhmm(delivery["digest_time_local"]) - lead_minutes
    back = 1 if at < 0 else 0
    digest_days = [CRON_DAYS[(CRON_DAYS.index(d) - back) % 7] for d in delivery["digest_days"]]
    weekly = _hhmm(delivery.get("weekly_summary_time_local") or DEFAULT_WEEKLY_TIME)
    return {"digest": Slot(at % (24 * 60), digest_days),
            "weekly": Slot(weekly, [delivery["weekly_summary_day"]])}


def _cron_days(numbers):
    """Cron day-of-week field: "0-5", "6", "1,3,5"."""
    nums = sorted(set(numbers))
    parts, i = [], 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        parts.append(str(nums[i]) if i == j else f"{nums[i]}-{nums[j]}" if j > i + 1 else f"{nums[i]},{nums[j]}")
        i = j + 1
    return ",".join(parts)


def _utc_minutes(local_minutes, offset, off_the_hour):
    utc = local_minutes - int(offset.total_seconds() // 60)
    if utc % 60 == 0:
        utc -= off_the_hour          # off the top of the hour, earlier rather than later
    return utc


def cron_line(local_minutes, days, offset, off_the_hour=3):
    """The UTC cron line firing at `local_minutes` past local midnight on each
    of `days` (weekday names) in a zone at UTC `offset`. When the UTC time
    falls on another calendar day, the day-of-week field moves with it."""
    shift, utc = divmod(_utc_minutes(local_minutes, offset, off_the_hour), 24 * 60)
    numbers = [(CRON_DAYS.index(d) + shift) % 7 for d in days]
    return f"{utc % 60} {utc // 60} * * {_cron_days(numbers)}"


def lines(delivery, lead_minutes, off_the_hour=3, start=None):
    """{"digest": [Line...], "weekly": [Line...]}: one per UTC offset the
    zone uses (America/New_York two, America/Phoenix one)."""
    tz = ZoneInfo(delivery["timezone"])
    out = {}
    for name, slot in slots(delivery, lead_minutes).items():
        out[name] = [Line(o, cron_line(slot.minutes, slot.days, o, off_the_hour)) for o in offsets(tz, start)]
    return out


def _offset_text(offset):
    total = int(offset.total_seconds() // 60)
    sign = "+" if total >= 0 else "-"
    return f"UTC{sign}{abs(total) // 60:02d}:{abs(total) % 60:02d}"


def block(name, delivery, lead_minutes, off_the_hour=3, start=None):
    """The generated `schedule:` block for workflow `name`, comment line
    included, indented for its place under `on:`."""
    slot = slots(delivery, lead_minutes)[name]
    local = f"{slot.minutes // 60:02d}:{slot.minutes % 60:02d}"
    out = [f"  {GENERATED_COMMENT}", "  schedule:"]
    for line in lines(delivery, lead_minutes, off_the_hour, start)[name]:
        out.append(f"    - cron: '{line.cron}'   # {local} {delivery['timezone']} when it is {_offset_text(line.offset)}")
    return "\n".join(out) + "\n"


# --- Rewriting the workflow files ----------------------------------------------

_SCHEDULE_RE = re.compile(r"^  schedule:\n(?:(?:    .*|\s*)\n)*", re.M)


def _span(text):
    """(start, end) of the schedule block in a workflow file, the generated
    comment line above it included when present."""
    m = _SCHEDULE_RE.search(text)
    if not m:
        raise ValueError("no '  schedule:' block under 'on:'")
    start, end = m.start(), m.end()
    # Trailing blank lines belong to what follows, not to the block.
    while text[:end].endswith("\n\n"):
        end -= 1
    above = text.rfind("\n", 0, start - 1) + 1
    if text[above:start].strip() == GENERATED_COMMENT:
        start = above
    return start, end


def current_block(path):
    text = Path(path).read_text()
    start, end = _span(text)
    return text[start:end]


def rewrite(text, new_block):
    """`text` with only its schedule block replaced by `new_block`."""
    start, end = _span(text)
    return text[:start] + new_block + text[end:]


def write(delivery, lead_minutes, off_the_hour=3, workflows=None):
    """Rewrite each workflow's schedule block; returns the names changed."""
    changed = []
    for name, path in (workflows or WORKFLOWS).items():
        text = Path(path).read_text()
        new = rewrite(text, block(name, delivery, lead_minutes, off_the_hour))
        if new != text:
            Path(path).write_text(new)
            changed.append(name)
    return changed


def mismatches(delivery, lead_minutes, off_the_hour=3, workflows=None):
    """{name: (in file, generated)} for each workflow whose block differs."""
    out = {}
    for name, path in (workflows or WORKFLOWS).items():
        have, want = current_block(path), block(name, delivery, lead_minutes, off_the_hour)
        if have != want:
            out[name] = (have, want)
    return out


# --- The slot guard ------------------------------------------------------------

def _cron_matches(cron, moment):
    """Does UTC datetime `moment` match a 'M H * * DOW' line (the only shape
    this module writes)?"""
    minute, hour, _, _, dow = cron.split()
    days = set()
    for part in dow.split(","):
        lo, _, hi = part.partition("-")
        days.update(range(int(lo), int(hi or lo) + 1))
    return moment.minute == int(minute) and moment.hour == int(hour) and (moment.weekday() + 1) % 7 in days


def scheduled_instant(cron, now):
    """The latest UTC minute at or before `now` that `cron` matches (a run
    starts late, never early, so its trigger lies behind it). None if the line
    has not matched in the past 8 days."""
    t = now.astimezone(timezone.utc).replace(second=0, microsecond=0)
    for _ in range(8 * 24 * 60):
        if _cron_matches(cron, t):
            return t
        t -= timedelta(minutes=1)
    return None


def intended_instants(name, delivery, lead_minutes, around):
    """The instants schedule `name` is meant to fire near UTC datetime
    `around`, one per local day either side. The digest's is the delivery time
    on that day minus the lead, in real elapsed time, so the morning the clocks
    jump it is still `lead_minutes` before delivery."""
    tz = ZoneInfo(delivery["timezone"])
    day = around.astimezone(tz).date()
    out = []
    for d in (day - timedelta(days=1), day, day + timedelta(days=1)):
        if name == "digest":
            deliver = datetime.combine(d, time(*divmod(_hhmm(delivery["digest_time_local"]), 60)), tz)
            out.append(deliver.astimezone(timezone.utc) - timedelta(minutes=lead_minutes))
        else:
            at = _hhmm(delivery.get("weekly_summary_time_local") or DEFAULT_WEEKLY_TIME)
            out.append(datetime.combine(d, time(*divmod(at, 60)), tz).astimezone(timezone.utc))
    return out


def on_slot(name, delivery, lead_minutes, window_minutes, now, cron=None, off_the_hour=3):
    """(True/False, reason). The run counts as fired at the instant its cron
    line last matched (`cron`, from github.event.schedule), or at `now` when
    that is unknown. It is on slot when that instant is within `window_minutes`
    of an intended fire time; the off-the-hour shift is allowed for."""
    fired = scheduled_instant(cron, now) if cron else now.astimezone(timezone.utc)
    if fired is None:
        return False, f"cron '{cron}' has not matched in the past 8 days"
    gap = min(abs(fired - t) for t in intended_instants(name, delivery, lead_minutes, fired))
    gap_minutes = gap.total_seconds() / 60
    ok = gap_minutes <= window_minutes + off_the_hour
    return ok, f"fired {fired:%Y-%m-%d %H:%M} UTC, {gap_minutes:.0f} min from the intended time"


def slot_guard(name, delivery, lead_minutes, window_minutes, now=None, cron=None, off_the_hour=3):
    """True when a --scheduled run should go ahead; otherwise logs the
    off-slot line and returns False (the caller exits 0)."""
    now = now or datetime.now(timezone.utc)
    ok, reason = on_slot(name, delivery, lead_minutes, window_minutes, now, cron, off_the_hour)
    if ok:
        print(f"[schedule] on-slot run for {delivery['timezone']} ({reason})")
    else:
        print(f"[schedule] off-slot run for {delivery['timezone']} (DST twin), exiting — {reason}")
    return ok
